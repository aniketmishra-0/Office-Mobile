/**
 * Form Design Templates — 12 distinct visual themes for public form pages.
 *
 * Each theme defines colors, typography, border radius, and layout style.
 * The theme is stored in `ui_config.design` and applied on the /f/[id] page.
 */

export interface FormTheme {
  id: string;
  name: string;
  description: string;
  preview: {
    bg: string;
    card: string;
    accent: string;
    text: string;
  };
  styles: {
    // Page background
    pageBg: string;
    // Card/container
    cardBg: string;
    cardBorder: string;
    cardShadow: string;
    cardRadius: string;
    // Typography
    fontFamily: string;
    titleColor: string;
    labelColor: string;
    textColor: string;
    placeholderColor: string;
    // Inputs
    inputBg: string;
    inputBorder: string;
    inputFocusBorder: string;
    inputFocusRing: string;
    inputRadius: string;
    inputText: string;
    // Button
    buttonBg: string;
    buttonText: string;
    buttonHover: string;
    buttonRadius: string;
    // Progress bar
    progressBg: string;
    progressFill: string;
    // Accent
    accentColor: string;
    // Meta text
    metaColor: string;
  };
}

